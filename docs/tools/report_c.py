"""Report, part C: experimental evaluation (the default-farm walk-through and one reading per benchmark suite).

Every number comes from farm_data (program outputs). Each sentence that interprets the numbers is
guarded by `claim(...)`: if a new benchmark run makes the sentence untrue, the generator stops and
says which one to revise.
"""
from farm_data import n0, n1, n2, n3
from facts import PACKERS, RESOURCES


def claim(condition, text):
    if not condition:
        raise SystemExit("A statement of the report no longer matches the data: %s\nRevise it in report_c.py." % text)


def ms(x):
    return "{:,.3f}".format(x) if x < 1 else ("{:,.2f}".format(x) if x < 100 else "{:,.0f}".format(x))


def plural(count, word):
    return "%d %s%s" % (count, word, "" if count == 1 else "s")


def seconds(x_ms):
    return "%s s" % n2(x_ms / 1000.0)


def write(r, D, F):
    r.h(1, "eval", "Experimental evaluation")
    setup(r, D, F)
    walkthrough(r, D, F)
    scaling(r, D, F)


# ------------------------------------------------------------------ setup

def setup(r, D, F):
    h = D.bench.header
    r.h(2, "setup", "Setup")
    r.p("**Machine and compiler.** All timings were measured on one machine: %s. The compiler was %s with the flags %s. "
        "The results of the walk-through (%s) do not depend on the machine; only the times do."
        % (h["Machine"], h["Compiler"], h["Build flags"].replace("RELEASE: ", ""), r.sec("walk")))
    r.p("**Data sets.** Three kinds of data are used. The *default scenario* (`data/default_scenario.json`) is the sample "
        "farm of %s. The *flat scenario* has the same farm with a constant order history, so that the results can be "
        "checked against the reference model. The *benchmark instances* are generated by the program from seeds: random "
        "graphs, knapsack problems, packing instances and scheduling instances of growing size, five seeds for every "
        "configuration." % r.sec("data"))
    r.p("**Method.** Every run is timed three times and the fastest is kept (a run over a second is timed once); the "
        "tables show medians over the five seeds. The *measured exponent* of an algorithm is the least-squares slope of "
        "ln(time) against ln(n) over the sizes whose median time is at least 0.05 ms, because smaller times are mostly "
        "timer and call overhead. A fit on two or three points is weak evidence and is labelled so. An exponent can only "
        "be compared with a polynomial bound; for exponential bounds the text reports node counts and growth factors instead.")
    r.table("tab:sources", "Where every number of this report comes from. Each file is written by the program; the report generator reads it and types nothing in by hand.",
            ["Used in", "Command that writes the file", "File"],
            [["The walk-through (%s)" % r.sec("walk"), "`farm_cli run --scenario data/default_scenario.json --packer ffd|bfd|ga --out ...`", "run_default_ffd.json, run_default_bfd.json, run_default_ga.json"],
             ["The comparison tables", "`farm_cli compare --scenario data/default_scenario.json --out ...`", "compare_default.json"],
             ["The flat farm", "`farm_cli run` and `farm_cli compare` with `data/flat_scenario.json`", "run_flat.json, compare_flat.json"],
             ["Scaling experiments (%s)" % r.sec("bench"), "`farm_cli bench`", "bench/results/*.csv and summary.md"],
             ["Test count", "`farm_tests`", "its output"],
             ["Figures", "`farm_app --screenshot <folder> --theme light`", "fig_*.png and ui_*.png"]],
            [4.2, 7.6, 4.6], size=8.5)


# ------------------------------------------------------------------ the walk-through

def walkthrough(r, D, F):
    c = F.cmp
    run = D.runs["default_ga"]
    r.h(2, "walk", "Walk-through of the default farm")
    r.p("This section follows one run of the pipeline on the default farm with the starting options of the application: "
        "automatic forecast selection, branch and bound, the genetic packer and EDF with lookahead. The figures and "
        "tables are the program’s own output. The comparison tables run every algorithm of a stage on the same input "
        "(`farm_cli compare`): the packers all pack the selection of branch and bound, and the schedulers all schedule the "
        "plan that First-Fit Decreasing and the refill step produce from it.")

    # ---- headline numbers
    r.h(3, "w_head", "The plan and its headline numbers")
    use = F.budget_use
    r.table("tab:headline", "Headline numbers of the final plan on the default farm.", ["Metric", "Value"],
            [["Relaxed optimum (crop selection, PKR per week)", "%s, proven optimal in %s nodes (root bound %s)" % (n1(F.relaxed), n0(F.bnb_nodes), n1(F.bnb_bound))],
             ["Plan value after packing and refill (PKR per week)", "%s, which is %s%% of the relaxed optimum" % (n1(F.plan_value), n2(F.plan_share))],
             ["Expected weekly profit (plan value without the contract bonuses)", "%s PKR" % n1(F.profit)],
             ["Budget use of the final plan", "; ".join("%s %s%%" % (name, n1(use[name])) for name in RESOURCES)],
             ["Space utilisation (placed tray area / shelf area)", "%s%%" % n2(F.space_use)],
             ["Contract reliability", "%d of %d contract lots on time" % (F.hard_on_time, F.hard_total)],
             ["Spot service", "%d of %d spot lots served (%s%%)" % (F.soft_served, F.soft_total, n1(F.spot_service))],
             ["Idle slot-weeks", str(F.idle)],
             ["Net over the plan (revenue minus penalties)", "%s PKR (revenue %s, penalties %s)" % (n0(F.net), n0(F.revenue), n0(F.penalties))]],
            [7.2, 9.2], size=9, source="farm_cli run --packer ga (run_default_ga.json).")
    claim(F.penalties == 0, "the final plan pays no penalties")
    unplaced = F.selected_trays - run["packing"]["placed"]
    r.p("The relaxed optimum is an upper bound on every plan, because branch and bound proved it and the knapsack sees only "
        "the total shelf area. The final plan reaches %s%% of it. The packer could not place %d of the %d selected trays; "
        "the refill step then added %s; the final plan has %d trays, %d fewer than the selection. All %d "
        "contract lots are delivered on time and no penalty is paid. The %d spot lots that are not served are the price of "
        "the budgets: the plan uses %s%% of the labour budget."
        % (n2(F.plan_share), unplaced, F.selected_trays, plural(F.final_trays - run["packing"]["placed"], "tray"), F.final_trays, F.dropped,
           F.hard_total, F.soft_total - F.soft_served, n1(use["labour"])))

    rows = []
    unused = [s["crop"] for s in run["selection"] if not (s["selected"] or s["trays"])]
    for s in run["selection"]:
        if s["selected"] or s["trays"]:
            rows.append([s["crop"], str(s["selected"]), str(s["trays"]), n2(s["weeklyKg"]), n2(s["demandKg"]), n1(s["value"])])
    rows.append(["**Total**", "**%d**" % F.selected_trays, "**%d**" % F.final_trays, "", "", "**%s**" % n1(F.plan_value)])
    r.table("tab:selection", "Trays per crop: the relaxed selection against the final plan. Crops without a tray in either column are left out (%s)." % ", ".join(unused),
            ["Crop", "Relaxed selection", "Final trays", "kg per week", "Demand kg per week", "Value PKR per week"], rows,
            [3.6, 2.6, 2.2, 2.6, 2.8, 2.6], size=9, align=["l", "r", "r", "r", "r", "r"],
            source="run_default_ga.json (selection).",
            notes="Weekly kg is the output of the final trays; demand includes the contract kilograms.")

    # ---- constraints
    r.h(3, "w_cons", "Pruning and the conflict graph")
    r.p("%d of the %d crop-shelf pairs are compatible, so %s%% of the possible assignments are ruled out before any "
        "optimiser runs. The conflict graph has %d edges (%d agronomic rules, %d height ratios, %d from shelves that no "
        "two crops can both use) and needs %d colours by all three algorithms, the exact search proving it in %d search nodes. "
        "%s shows the graph and the compatibility table." % (F.pairs_ok, F.pairs_total, n1(F.pruned), F.edges, F.edges_explicit,
                                                          F.edges_height, F.edges_none, F.colours[0], F.exact_nodes, r.ref("fig:cons")))
    r.figure("fig:cons", D.fig("fig_constraints"),
             "The Constraints tab. Left: the conflict graph (a node is a crop and shows its DSATUR colour class; red edges are agronomic rules, orange edges height ratios). Right: the pruning numbers. Below: which crop may stand on which shelf.",
             source="farm_app --screenshot, data/default_scenario.json.")

    # ---- forecasts
    r.h(3, "w_fore", "Forecasts")
    chosen = run["forecast"][0]
    fc = F.cmp
    rows = []
    for name in ("seasonal naive", "moving average", "simple exponential smoothing", "Holt-Winters"):
        rows.append([name, n2(fc("Forecast", name, "MAE")), n2(fc("Forecast", name, "RMSE")), n2(fc("Forecast", name, "sMAPE %")),
                     str(int(fc("Forecast", name, "chosen for crops")))])
    r.table("tab:forecast", "Hold-out errors of the four forecasting methods on the default farm, averaged over the crops (MAE and RMSE in kg per week), and the number of crops each method was chosen for.",
            ["Method", "MAE", "RMSE", "sMAPE %", "Chosen for crops"], rows, [6.0, 2.4, 2.4, 2.8, 2.8], size=9,
            align=["l", "r", "r", "r", "r"], source="farm_cli compare (compare_default.json, Forecast).")
    best = min(("seasonal naive", "moving average", "simple exponential smoothing", "Holt-Winters"), key=lambda m: fc("Forecast", m, "MAE"))
    claim(best == "Holt-Winters", "Holt-Winters has the lowest mean error on the default farm")
    lettuce = {h["method"]: h for h in chosen["holdout"]}
    claim(chosen["crop"] == "Lettuce" and chosen["method"] == "moving average", "the Forecast tab shows lettuce with the moving average chosen")
    r.p("Holt-Winters has the lowest error on average (MAE %s kg per week against %s for seasonal naive) and is chosen for "
        "%d crops, but the rule decides crop by crop: for lettuce the last %d weeks are predicted best by a moving average "
        "of the last %s weeks (MAE %s, against %s for Holt-Winters and %s for seasonal naive; the two best are within 0.01 of each other, and the rule keeps the earlier method on a tie). %s shows that crop."
        % (n2(fc("Forecast", "Holt-Winters", "MAE")), n2(fc("Forecast", "seasonal naive", "MAE")),
           int(fc("Forecast", "Holt-Winters", "chosen for crops")), chosen["holdoutLength"], chosen["parameters"].replace("k=", ""),
           n3(lettuce["moving average"]["mae"]), n3(lettuce["Holt-Winters"]["mae"]), n3(lettuce["seasonal naive"]["mae"]), r.ref("fig:fore")))
    claim(abs(lettuce["moving average"]["mae"] - lettuce["Holt-Winters"]["mae"]) < 0.01 and lettuce["moving average"]["mae"] < lettuce["Holt-Winters"]["mae"],
          "for lettuce the moving average and Holt-Winters are within 0.01 and the moving average is the lower")
    r.figure("fig:fore", D.fig("fig_forecast"),
             "The Forecast tab for lettuce: weekly spot demand, the hold-out predictions of the four methods, the forecast of the chosen method (moving average, k = 4) and the contract level.",
             source="farm_app --screenshot, data/default_scenario.json.")

    # ---- crop selection
    r.h(3, "w_sel", "Crop selection")
    rows = []
    for name in ("greedy", "dynamic programming", "branch and bound"):
        row = c.stages["Crop selection"][name]
        rows.append([name, n1(row["value"]), n2(row["% of best"]), n1(row["bound"]) if row["bound"] else "–",
                     n0(row["nodes"]) if row["nodes"] else "–", n0(row["states"]) if row["states"] else "–",
                     "yes" if row["proven"] else "no", ms(row["ms"]), row["note"] or ""])
    r.table("tab:selcmp", "Crop selection: the three algorithms on the default farm.",
            ["Algorithm", "Value", "% of best", "Root bound", "Nodes", "DP cells", "Proven", "ms", "Note"], rows,
            [3.0, 1.7, 1.4, 1.7, 1.2, 1.7, 1.2, 1.5, 3.0], size=8, align=["l", "r", "r", "r", "r", "r", "c", "r", "l"],
            source="farm_cli compare (compare_default.json, Crop selection).")
    claim(F.dp_pct < 50 and F.greedy_pct > 95, "the DP is poor because of the coarse grid and greedy is within 5% of the optimum")
    r.p("Branch and bound proves its optimum in %s nodes and %s ms. Greedy takes %s ms and reaches %s%% of the optimum. "
        "Dynamic programming reaches only %s%% and needs %s ms: with all five resources the exact grid would have far too "
        "many cells, so it is coarsened (“%s”); every tray’s labour then rounds up to a seventeenth of the "
        "budget and the plan holds at most 17 trays. The table still has %s cells. This is the expected behaviour and the "
        "reason dynamic programming is not the main solver: it is pseudo-polynomial in each budget and exponential in the "
        "number of budgets (%s). With only one or two budgets switched on, it is exact and matches branch and bound."
        % (n0(F.bnb_nodes), ms(c("Crop selection", "branch and bound", "ms")), ms(c("Crop selection", "greedy", "ms")), n2(F.greedy_pct),
           n1(F.dp_pct), ms(c("Crop selection", "dynamic programming", "ms")), F.dp_note, n0(F.dp_states), r.sec("bench_dims")))

    # ---- packing
    r.h(3, "w_pack", "Packing")
    rows = []
    for name in PACKERS:
        row = c.stages["Packing"][name]
        rows.append([name, n0(row["trays"]), n0(row["placed"]), n1(row["value"]), n0(row["shelves used"]), n2(row["utilisation %"]), ms(row["ms"])])
    r.table("tab:packcmp", "Packing: the three algorithms on the trays selected by branch and bound.",
            ["Algorithm", "Trays", "Placed", "Value", "Shelves used", "Utilisation %", "ms"], rows,
            [4.4, 1.6, 1.8, 2.2, 2.2, 2.4, 1.8], size=9, align=["l", "r", "r", "r", "r", "r", "r"],
            source="farm_cli compare (compare_default.json, Packing).")
    ffd, bfd, ga = (F.placed[p] for p in PACKERS)
    claim(ga > ffd > bfd, "the genetic algorithm places most trays and Best-Fit the fewest")
    ga_ms, ffd_ms = (c("Packing", PACKERS[2], "ms"), c("Packing", PACKERS[0], "ms"))
    r.p("Packing is the only stage where the plan can fall below the relaxed optimum, and the packers differ clearly. Of the %d selected trays First-Fit Decreasing places "
        "%d, Best-Fit Decreasing %d and the genetic algorithm %d; neither greedy policy dominates the other in general, "
        "but here First-Fit is better. The genetic algorithm is never worse than the two greedy packers, because their "
        "layouts are in its first population and the best individuals always survive; it needed %d generations "
        "and %s ms, about %s times as long as First-Fit Decreasing. After packing, the refill step spends the freed budget "
        "again: the genetic packer’s %d placed trays become %d, a plan worth %s PKR per week (%s%% of the relaxed "
        "optimum). With First-Fit Decreasing the same pipeline ends at %s%% and with Best-Fit Decreasing at %s%%. "
        "%s shows the final layout and %s the convergence of the genetic search."
        % (int(F.selected_by_bnb), ffd, bfd, ga, F.ga_generations, ms(ga_ms), n0(ga_ms / ffd_ms), run["packing"]["placed"], F.final_trays,
           n0(F.plan_value), n2(F.plan_share), n2(F.by_packer[PACKERS[0]]["share"]), n2(F.by_packer[PACKERS[1]]["share"]),
           r.ref("fig:layout"), r.ref("fig:conv")))
    r.figure("fig:layout", D.fig("fig_layout"),
             "The Layout tab: the final plan on the sixteen shelves of the four racks, to scale, each tray labelled with its crop. Percentages under a shelf show how full it is.",
             source="farm_app --screenshot, data/default_scenario.json, genetic packer.")
    r.figure("fig:conv", D.fig("fig_convergence"),
             "Convergence of the genetic algorithm: the value of the best individual in each generation.",
             source="farm_app --screenshot, data/default_scenario.json.", width_cm=12.5)

    # ---- scheduling
    r.h(3, "w_sched", "Scheduling")
    rows = []
    for name in ("EDF", "EDF with lookahead", "exact"):
        row = c.stages["Scheduling"][name]
        rows.append([name, "%d / %d" % (row["hard on time"], row["hard lots"]), "%d / %d" % (row["soft served"], row["soft lots"]),
                     n0(row["idle slot-weeks"]), n0(row["revenue"]), n0(row["penalties"]), n0(row["net"]), ms(row["ms"])])
    r.table("tab:sched", "Scheduling: the three algorithms on the same plan (revenue, penalties and net in PKR).",
            ["Algorithm", "Contract lots on time", "Spot lots served", "Idle slot-weeks", "Revenue", "Penalties", "Net", "ms"], rows,
            [3.0, 2.2, 2.2, 1.8, 2.0, 1.7, 2.0, 1.5], size=8.5, align=["l", "r", "r", "r", "r", "r", "r", "r"],
            source="farm_cli compare (compare_default.json, Scheduling).",
            notes="The exact search is limited to crops with at most 22 lots. For %s crops it was skipped and the lookahead schedule is shown, so its row equals the lookahead row; it earns its place on the small instances of %s." %
                  (F.exact_fell_back.split()[0], r.sec("bench_exact")))
    claim(F.edf_missed > 0 and F.look["hard"] == F.look["hard_total"], "lookahead delivers every contract lot and EDF misses some")
    claim(F.edf["soft"] > F.look["soft"] and F.net_gain > 0, "EDF serves more spot lots but lookahead has the higher net revenue")
    r.p("Earliest deadline first fills every free slot with the lot due soonest. It serves %d spot lots (against %d) and "
        "keeps %d slot-weeks idle (against %d), but a contract lot released a week later then finds every slot busy for "
        "the whole cycle, and %d of the %d contract lots are missed, which costs %s PKR in penalties. The lookahead "
        "scheduler leaves a slot idle when a spot batch would cost a contract delivery that was otherwise still "
        "achievable: it delivers all %d contract lots on time, gives up %d spot lots, and its net revenue is %s PKR "
        "higher (%s against %s). This is the conflict of requirements of characteristic 1 in %s. %s shows the timeline of the final plan."
        % (F.edf["soft"], F.look["soft"], F.edf["idle"], F.look["idle"], F.edf_missed, F.hard_total, n0(F.edf["penalties"]),
           F.hard_total, F.spot_given_up, n0(F.net_gain), n0(F.look["net"]), n0(F.edf["net"]), r.ref("tab:ccp"), r.ref("fig:sched")))
    r.figure("fig:sched", D.fig("fig_schedule"),
             "The Schedule tab: one bar per batch from planting to harvest, one row per slot, grouped by crop. A thick outline marks a contract delivery; the red line is the end of the planting horizon.",
             source="farm_app --screenshot, data/default_scenario.json, EDF with lookahead.")

    # ---- the flat farm
    r.h(3, "w_flat", "The flat farm and the reference model")
    fl = D.compare["flat"]
    r.table("tab:flat", "Results on the flat farm. They equal the golden numbers of the plan’s Appendix A, which the tests assert and which the independent reference model computed.",
            ["Quantity", "Value"],
            [["Relaxed optimum", "%s PKR per week, proven in %s nodes" % (n1(F.flat_relaxed), n0(F.flat_nodes))],
             ["First-Fit Decreasing", "places %d of %d trays (%d do not fit)" % (F.flat_ffd_placed, F.flat_trays, F.flat_ffd_unplaced)],
             ["Dynamic programming", "%s%% of the optimum (grid coarsened, as on the default farm)" % n2(F.flat_dp_pct)],
             ["EDF against lookahead",
              "%d against %d contract lots on time of %d; net %s against %s PKR" % (
                  fl("Scheduling", "EDF", "hard on time"), fl("Scheduling", "EDF with lookahead", "hard on time"),
                  fl("Scheduling", "EDF", "hard lots"), n0(fl("Scheduling", "EDF", "net")), n0(fl("Scheduling", "EDF with lookahead", "net")))]],
            [5.0, 11.4], size=9, source="run_flat.json, compare_flat.json.")


# ------------------------------------------------------------------ scaling experiments

def _cap(suite):
    return "Median time (left) and quality (right) of every algorithm of the suite `%s`. %s" % (suite.name, suite.legend)


def scaling(r, D, F):
    S = D.bench.suites
    e = F.exp
    r.h(2, "bench", "Scaling experiments")
    r.p("Ten benchmark suites time the algorithms on instances of growing size (`farm_cli bench`, %s). Each of the "
        "following subsections gives the instances, the chart that the application draws from the same files "
        "(the Compare tab) and a short reading. %s collects the measured exponents beside the predicted growth."
        % (r.sec("setup"), r.ref("tab:measured")))

    # ---- colouring
    s = S["colouring"]
    r.h(3, "b_col", "Constraint colouring (colouring)")
    r.p("*%s*" % s.description)
    small = {}                       # (n, edge probability, seed) -> colours used by each algorithm
    for row in s.rows:
        if row["n"] <= 20:
            small.setdefault((row["n"], row["param"], row["seed"]), {})[row["algo"]] = row["quality"]
    exact_rows = [row for row in s.rows if row["algo"] == "exact"]
    claim(exact_rows and all(row["aux2"] == 1 for row in exact_rows), "the exact search proved its result on every small instance")
    wp_worse = sum(1 for v in small.values() if v["wp"] > v["exact"])
    ds_worse = sum(1 for v in small.values() if v["dsatur"] > v["exact"])
    excess = max(max(v["wp"] - v["exact"], v["dsatur"] - v["exact"]) for v in small.values())
    claim(excess == 1 and all(v["wp"] >= v["exact"] and v["dsatur"] >= v["exact"] for v in small.values()) and ds_worse < wp_worse,
          "a heuristic is never better than the optimum, loses at most one colour, and DSATUR loses less often than Welsh-Powell")
    wp50, ds50 = s.series("wp", param=50), s.series("dsatur", param=50)
    claim(wp50[-1][0] == 400 and ds50[-1][0] == 400 and ds50[-1][2] < wp50[-1][2], "DSATUR uses fewer colours than Welsh-Powell at 400 vertices and 50%")
    r.p("Up to 20 vertices the exact search gives the true optimum. On the %d such instances Welsh-Powell used one colour "
        "more than the optimum on %d of them and DSATUR on %d; otherwise both were optimal. At 400 vertices and 50%% edge "
        "probability Welsh-Powell uses %s colours in %s ms and DSATUR %s colours in %s ms: DSATUR saves %s colours and costs "
        "%s times the time. The measured exponents are %s for Welsh-Powell at 50%% (two points; none at 10%% and 30%%, where "
        "only the largest size reaches 0.05 ms) and %s, %s and %s for DSATUR, against predicted growth of about n² and "
        "n³: the implementation recomputes the saturation of every vertex in every round, as specified."
        % (len(small), wp_worse, ds_worse, n0(wp50[-1][2]), ms(wp50[-1][1]), n0(ds50[-1][2]), ms(ds50[-1][1]),
           n0(wp50[-1][2] - ds50[-1][2]), n0(ds50[-1][1] / wp50[-1][1]), n2(e.wp50), n2(e.dsatur[0]), n2(e.dsatur[1]), n2(e.dsatur[2])))
    r.figure("fig:b_col", D.fig("fig_bench_colouring"), _cap(s), source="bench/results/colouring.csv, summary.md.", width_cm=13.5)

    # ---- forecast
    s = S["forecast"]
    r.h(3, "b_fore", "Forecasting (forecast)")
    r.p("*%s*" % s.description)
    q = {(a, p): v for a in ("naive", "ma", "ses", "hw") for p, _, v in s.series(a, x="param")}
    tm = {a: s.series(a, x="param")[0][1] for a in ("naive", "ma", "ses", "hw")}
    claim(q["hw", 5] == min(q[a, 5] for a in ("naive", "ma", "ses", "hw")), "Holt-Winters has the lowest error at 5% noise")
    claim(q["hw", 30] > min(q["ma", 30], q["ses", 30]) and q["naive", 30] == max(q[a, 30] for a in ("naive", "ma", "ses", "hw")),
          "at 30% noise the simple smoothers beat Holt-Winters and seasonal naive is worst")
    claim(tm["hw"] > 10 * max(tm["naive"], tm["ma"], tm["ses"]), "Holt-Winters costs more than ten times the others")
    r.p("The score is the mean absolute error as a percentage of the mean demand. At 5%% noise Holt-Winters has the lowest "
        "error (%s%%, against %s%% for seasonal naive, %s%% for the moving average and %s%% for simple exponential "
        "smoothing); at 30%% noise the order has reversed: smoothing (%s%%) and the moving average (%s%%) beat "
        "Holt-Winters (%s%%) and seasonal naive (%s%%), which carries last year’s noise into the forecast. "
        "Holt-Winters also costs most: %s ms to fit the 24 histories, against %s ms or less for the others. No method wins everywhere, "
        "which is the reason for choosing by hold-out error crop by crop."
        % (n2(q["hw", 5]), n2(q["naive", 5]), n2(q["ma", 5]), n2(q["ses", 5]), n2(q["ses", 30]), n2(q["ma", 30]), n2(q["hw", 30]),
           n2(q["naive", 30]), ms(tm["hw"]), ms(max(tm["naive"], tm["ma"], tm["ses"]))))
    r.figure("fig:b_fore", D.fig("fig_bench_forecast"), _cap(s), source="bench/results/forecast.csv, summary.md.", width_cm=13.5)

    # ---- knap_1d
    s = S["knap_1d"]
    r.h(3, "b_k1", "One budget (knap_1d)")
    r.p("*%s*" % s.description)
    g, dp, bb = s.series("greedy"), s.series("dp"), s.series("bnb")
    claim(all(x[2] == 100 for x in g[1:]) and g[0][2] > 99, "greedy is optimal from 100 copies on and within 1% at 50")
    claim(all(r_["aux2"] == 1 for r_ in s.rows if r_["algo"] == "bnb"), "branch and bound proved every knap_1d instance")
    nodes = [s.median_of("aux1", "bnb", n=n) for n, _, _ in bb]
    r.p("Greedy is within %s%% of the optimum at 50 copies and optimal from 100 copies on, and takes at most %s ms. "
        "Dynamic programming takes %s ms at 1,600 copies with an exponent of %s (five points): its table has about N² "
        "cells, because the capacity is half the total weight and so grows with N. Branch and bound takes %s ms and has "
        "exponent %s; it proved every instance optimal, with %s to %s nodes (median): with one budget the fractional "
        "bound prunes almost everything."
        % (n2(100 - g[0][2]), ms(g[-1][1]), ms(dp[-1][1]), n2(e.dp), ms(bb[-1][1]), n2(e.bnb_1d), n0(min(nodes)), n0(max(nodes))))
    r.figure("fig:b_k1", D.fig("fig_bench_knap_1d"), _cap(s), source="bench/results/knap_1d.csv, summary.md.", width_cm=13.5)

    # ---- knap_dims
    s = S["knap_dims"]
    r.h(3, "bench_dims", "Growing number of budgets (knap_dims)")
    r.p("*%s*" % s.description)
    dp = s.series("dp", x="param")
    bb = s.series("bnb", x="param")
    gr = s.series("greedy", x="param")
    ratios = [b[1] / a[1] for a, b in zip(dp, dp[1:])]
    cells = [s.median_of("aux1", "dp", param=p) for p in (1, 2, 3, 4)]
    nodes = [s.median_of("aux1", "bnb", param=p) for p in (1, 2, 3, 4)]
    claim(all(b / a == 25 for a, b in zip(cells, cells[1:])) and all(15 < x < 30 for x in ratios), "the DP table grows 25 times per budget and its time about as much")
    claim(gr[0][2] > gr[-1][2], "greedy loses value as budgets are added")
    r.p("The table of dynamic programming grows from %s cells with one budget to %s cells with four, a factor of 25 for every "
        "added budget, and its time follows: %s ms with one budget, then %s, %s and %s ms with two, three and four, factors "
        "of %s, %s and %s. This is the exponential dependence on the number of budgets that makes dynamic programming "
        "unusable for the farm problem. Branch and bound stays between %s and %s ms with %s to %s nodes. Greedy loses "
        "value as budgets are added: %s%% of the optimum with one budget, %s%% with four."
        % (n0(cells[0]), n0(cells[-1]), ms(dp[0][1]), ms(dp[1][1]), ms(dp[2][1]), ms(dp[3][1]),
           n1(ratios[0]), n1(ratios[1]), n1(ratios[2]), ms(bb[0][1]), ms(bb[-1][1]), n0(nodes[0]), n0(nodes[-1]), n2(gr[0][2]), n2(gr[-1][2])))
    r.figure("fig:b_dims", D.fig("fig_bench_knap_dims"), _cap(s), source="bench/results/knap_dims.csv, summary.md.", width_cm=13.5)

    # ---- knap_farm
    s = S["knap_farm"]
    r.h(3, "b_kf", "The farm’s own knapsack problem (knap_farm)")
    r.p("*%s*" % s.description)
    bb, gr = s.series("bnb"), s.series("greedy")
    nodes = [s.median_of("aux1", "bnb", n=n) for n, _, _ in bb]
    claim(all(r_["aux2"] == 1 for r_ in s.rows if r_["algo"] == "bnb"), "branch and bound proved every knap_farm instance")
    r.p("Branch and bound proved every instance optimal, with %s nodes at 6, 12, 18 and 24 crops respectively, in %s to %s ms. Its "
        "exponent is %s from four points, which describes the trend over this range and says nothing about the "
        "exponential worst case. Greedy reaches %s to %s%% of the root bound and branch and bound %s to %s%%: on these "
        "instances the heuristic is within about %s points of the optimum."
        % ("; ".join(n0(x) for x in nodes), ms(bb[0][1]), ms(bb[-1][1]), n2(e.bnb_farm), n2(min(x[2] for x in gr)), n2(max(x[2] for x in gr)),
           n2(min(x[2] for x in bb)), n2(max(x[2] for x in bb)), n1(max(b[2] - g_[2] for b, g_ in zip(bb, gr)))))
    r.figure("fig:b_kf", D.fig("fig_bench_knap_farm"), _cap(s), source="bench/results/knap_farm.csv, summary.md.", width_cm=13.5)

    # ---- pack_tight, pack_loose
    for key, name, label in (("pack_tight", "b_pt", "Tight packing (pack_tight)"), ("pack_loose", "b_pl", "Loose packing (pack_loose)")):
        s = S[key]
        r.h(3, name, label)
        r.p("*%s*" % s.description)
        ffd, bfd, ga_ = s.series("ffd"), s.series("bfd"), s.series("ga")
        ex = (e.ffd, e.bfd, e.ga) if key == "pack_tight" else (e.ffd_loose, e.bfd_loose, e.ga_loose)
        if key == "pack_tight":
            claim(all(x[2] == 100 for x in ga_) and max(x[2] for x in ffd + bfd) < 100, "tight: the genetic algorithm places everything, the greedy packers do not")
            r.p("The score is the placed area as a percentage of the tray area. The genetic algorithm places everything "
                "(%s%%) at every size; First-Fit Decreasing places %s to %s%% and Best-Fit Decreasing %s to %s%% (medians). The "
                "price is time: at 800 trays the genetic algorithm takes %s while First-Fit Decreasing takes %s ms, a "
                "factor of %s. The exponents are %s (First-Fit), %s (Best-Fit) and %s (genetic), all near the predicted n² "
                "because the number of shelves grows with the number of trays; the genetic algorithm’s cost is a fixed "
                "number of generations and individuals times one decoding, so its exponent is that of the packers it contains."
                % (n0(ga_[0][2]), n1(min(x[2] for x in ffd)), n1(max(x[2] for x in ffd)), n1(min(x[2] for x in bfd)), n1(max(x[2] for x in bfd)),
                   seconds(ga_[-1][1]), ms(ffd[-1][1]), n0(ga_[-1][1] / ffd[-1][1]), n2(ex[0]), n2(ex[1]), n2(ex[2])))
        else:
            claim(all(x[2] == 100 for x in ffd + bfd + ga_), "loose: every packer places everything")
            r.p("With room to spare all three algorithms place every tray at every size, so the greedy packers suffice and "
                "the genetic algorithm is pure cost: %s against %s ms for First-Fit Decreasing at 800 trays. The exponents are "
                "%s, %s and %s." % (seconds(ga_[-1][1]), ms(ffd[-1][1]), n2(ex[0]), n2(ex[1]), n2(ex[2])))
        r.figure("fig:" + name, D.fig("fig_bench_" + key), _cap(s), source="bench/results/%s.csv, summary.md." % key, width_cm=13.5)

    # ---- sched
    s = S["sched"]
    r.h(3, "b_s", "Scheduling at growing size (sched)")
    r.p("*%s*" % s.description)
    edf, la = s.series("edf"), s.series("lookahead")
    claim(all(x[2] == edf[1][2] for x in edf[1:]) and edf[0][2] > edf[1][2] and all(x[2] == 100 for x in la), "EDF drops after 5 slots and stays level; lookahead is at 100%")
    r.p("The quality is the share of contract lots delivered on time. Earliest deadline first serves %s%% of them with 5 "
        "slots and %s%% from 10 slots up; lookahead serves all of them at every size. Lookahead costs more, %s ms at 80 "
        "slots against %s ms, because of the admission test. Its exponent is %s from two points; EDF has no exponent "
        "(only one size reaches 0.05 ms)." % (n2(edf[0][2]), n2(edf[1][2]), ms(la[-1][1]), ms(edf[-1][1]), n2(e.look)))
    r.figure("fig:b_s", D.fig("fig_bench_sched"), _cap(s), source="bench/results/sched.csv, summary.md.", width_cm=13.5)

    # ---- sched_window
    s = S["sched_window"]
    r.h(3, "b_w", "The lookahead window (sched_window)")
    r.p("*%s*" % s.description)
    w = s.series("lookahead", x="param")
    claim(w[0][2] < w[1][2] < w[2][2] == 100 and all(x[2] == 100 for x in w[2:]), "the window needs two weeks to reach 100%")
    r.p("With no window, %s%% of the contract lots are on time; with one week %s%%; from two weeks on, all of them. The "
        "default window, the crop’s cycle (5 weeks), is therefore more than these instances need: a short window "
        "already protects every contract. Time grows slowly with the window, from %s to %s ms."
        % (n2(w[0][2]), n2(w[1][2]), ms(w[0][1]), ms(w[-1][1])))
    r.figure("fig:b_w", D.fig("fig_bench_sched_window"), _cap(s), source="bench/results/sched_window.csv, summary.md.", width_cm=13.5)

    # ---- sched_exact
    s = S["sched_exact"]
    r.h(3, "bench_exact", "Exact scheduling on small instances (sched_exact)")
    r.p("*%s*" % s.description)
    edf, la, ex_ = s.series("edf"), s.series("lookahead"), s.series("exact")
    claim(all(x[2] == 100 for x in la + ex_) and edf[0][2] == 100 and all(x[2] < 0 for x in edf[1:]), "lookahead and exact are at 100%, EDF is negative from 12 lots")
    r.p("Lookahead reaches the optimum at all four sizes. Earliest deadline first reaches it at %d lots and then falls to %s%%, "
        "%s%% and %s%%: a negative value means that its penalties for missed contract lots exceed its revenue. The exact search "
        "needs %s to %s ms, a factor of %s between %d and %d lots, which is consistent with exponential growth, and none "
        "of its runs came near the node limit."
        % (edf[0][0], n2(edf[1][2]), n2(edf[2][2]), n2(edf[3][2]), ms(ex_[0][1]), ms(ex_[-1][1]), n1(ex_[-1][1] / ex_[0][1]), ex_[0][0], ex_[-1][0]))
    r.figure("fig:b_x", D.fig("fig_bench_sched_exact"), _cap(s), source="bench/results/sched_exact.csv, summary.md.", width_cm=13.5)

    # ---- measured against predicted
    r.h(3, "b_sum", "Measured against predicted growth")

    def exs(suite, algo, param=None):
        value, points = S[suite].exponent(algo, param)
        return "none" if value is None else "%s (%d)" % (n2(value), points)

    dp_dims = S["knap_dims"].series("dp", x="param")
    ratio_text = ", ".join(n1(b[1] / a[1]) for a, b in zip(dp_dims, dp_dims[1:]))
    rows = [
        ["Welsh-Powell", "colouring, vertices; 10 / 30 / 50%", "about n²", " / ".join(exs("colouring", "wp", p) for p in (10, 30, 50))],
        ["DSATUR", "colouring, vertices; 10 / 30 / 50%", "about n³", " / ".join(exs("colouring", "dsatur", p) for p in (10, 30, 50))],
        ["Exact colouring", "colouring, vertices (at most 20)", "exponential", "none: every run under 0.05 ms"],
        ["Greedy knapsack", "knap_1d, knap_farm", "N log N", "%s, %s" % (exs("knap_1d", "greedy"), exs("knap_farm", "greedy"))],
        ["Dynamic programming", "knap_1d, copies (one budget)", "about N²", exs("knap_1d", "dp")],
        ["Dynamic programming", "knap_dims, budgets (n fixed)", "×25 per added budget", "no exponent; time ratios %s" % ratio_text],
        ["Branch and bound", "knap_1d, copies", "exponential worst case", exs("knap_1d", "bnb")],
        ["Branch and bound", "knap_farm, crops", "exponential worst case", exs("knap_farm", "bnb")],
        ["First-Fit Decreasing", "pack_tight / pack_loose, trays", "about n²", "%s / %s" % (exs("pack_tight", "ffd"), exs("pack_loose", "ffd"))],
        ["Best-Fit Decreasing", "pack_tight / pack_loose, trays", "about n²", "%s / %s" % (exs("pack_tight", "bfd"), exs("pack_loose", "bfd"))],
        ["Genetic algorithm", "pack_tight / pack_loose, trays", "about n²", "%s / %s" % (exs("pack_tight", "ga"), exs("pack_loose", "ga"))],
        ["EDF", "sched, slots", "about k²", exs("sched", "edf")],
        ["EDF with lookahead", "sched, slots", "about k²", exs("sched", "lookahead")],
        ["Exact scheduling", "sched_exact, lots", "exponential", "none: every run under 0.05 ms"],
    ]
    r.table("tab:measured", "Measured exponent (number of points) beside the predicted growth. A fit on two or three points is weak evidence.",
            ["Algorithm", "Suite, and what grows", "Predicted growth", "Measured exponent (points)"], rows, [3.4, 5.0, 3.4, 4.6], size=8.5,
            source="bench/results/summary.md.")
    claim(S["colouring"].exponent("exact", 50)[0] is None and S["sched_exact"].exponent("exact")[0] is None and S["sched"].exponent("edf")[0] is None,
          "the exact searches and EDF have no exponent")
    pairs = [("First-Fit Decreasing", e.ffd, 2), ("Best-Fit Decreasing", e.bfd, 2), ("genetic algorithm", e.ga, 2),
             ("dynamic programming", e.dp, 2), ("lookahead", e.look, 2), ("Welsh-Powell", e.wp50, 2)] + \
            [("DSATUR", x, 3) for x in e.dsatur]
    claim(all(abs(v - predicted) < 0.5 for _, v, predicted in pairs), "every measured exponent is within 0.5 of its predicted value")
    nodes = [S["knap_farm"].median_of("aux1", "bnb", n=n) for n in (6, 12, 18, 24)]
    r.p("Where a polynomial bound exists the measured exponents are close to it. The packers measure between %s and %s "
        "(predicted about 2; slightly lower, probably because small instances carry a constant overhead), dynamic programming %s "
        "in the number of copies (about 2), lookahead %s from two points (about 2), Welsh-Powell %s from two points "
        "(about 2) and DSATUR between %s and %s (about 3). The exponential algorithms are reported by counts instead: the "
        "dynamic-programming table grows by a factor of 25 per budget, and branch and bound visits %s to %s nodes on the "
        "farm instances."
        % (n2(min(e.ffd, e.bfd, e.ga, e.ffd_loose, e.bfd_loose, e.ga_loose)), n2(max(e.ffd, e.bfd, e.ga, e.ffd_loose, e.bfd_loose, e.ga_loose)),
           n2(e.dp), n2(e.look), n2(e.wp50), n2(min(e.dsatur)), n2(max(e.dsatur)), n0(min(nodes)), n0(max(nodes))))
